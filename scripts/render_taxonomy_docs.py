"""Render the RCA and lifecycle taxonomies from src/lambda/common/taxonomy.py as Markdown.

Documentation embeds the output between `<!-- taxonomy:start -->` and `<!-- taxonomy:end -->`
markers so definitions stay single-sourced. `--check` fails when a file's block is stale;
`--write` regenerates it.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src" / "lambda"))

from common.taxonomy import LIFECYCLE, RCA, UNCLASSIFIED  # noqa: E402

START = "<!-- taxonomy:start -->"
END = "<!-- taxonomy:end -->"


def render_markdown() -> str:
    """Return the generated taxonomy section."""
    parts = [
        "<!-- Generated by scripts/render_taxonomy_docs.py; edit src/lambda/common/taxonomy.py. -->"
    ]
    for taxonomy in (RCA, LIFECYCLE):
        parts += [
            "",
            f"### {taxonomy.title} categories ({len(taxonomy.categories)})",
            "",
            f"JSON keys: `{taxonomy.category_key}`, `{taxonomy.reason_key}`.",
            "",
            taxonomy.render_markdown_table(),
        ]
    parts += [
        "",
        f"`{UNCLASSIFIED}` is not a category. It is recorded only when a classifier reply is still "
        "invalid after one corrective prompt, with a short explanation as the reason.",
    ]
    return "\n".join(parts)


def replace_block(text: str, block: str) -> str:
    """Return `text` with the content between the markers replaced by `block`."""
    start = text.find(START)
    end = text.find(END)
    if start == -1 or end == -1 or end < start:
        raise ValueError(f"File must contain {START} followed by {END}")
    return f"{text[: start + len(START)]}\n{block}\n{text[end:]}"


def main(argv: Sequence[str] | None = None) -> int:
    """Entry point."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", type=Path, help="Fail if FILE's taxonomy block is out of date.")
    group.add_argument("--write", type=Path, help="Regenerate FILE's taxonomy block in place.")
    args = parser.parse_args(argv)
    block = render_markdown()
    if args.check is None and args.write is None:
        sys.stdout.write(block + "\n")
        return 0
    path: Path = args.check or args.write
    try:
        text = path.read_text(encoding="utf-8")
        updated = replace_block(text, block)
    except (OSError, ValueError) as exc:
        sys.stderr.write(f"{exc}\n")
        return 2
    if args.write is not None:
        path.write_text(updated, encoding="utf-8")
        return 0
    if updated != text:
        sys.stderr.write(f"{path} taxonomy block is out of date; run with --write.\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
